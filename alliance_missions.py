def generate_daily_missions(seed_date: str = None) -> List[dict]:
    """
    Generate 10 daily missions with varied ranks.
    Seed by date so all alliances see the same pool (just different selections).
    Rank distribution: 3×D, 3×C, 2×B, 1×A, 1×S
    """
    if seed_date is None:
        seed_date = datetime.utcnow().strftime("%Y-%m-%d")

    rng = random.Random(seed_date)   # Deterministic for the day

    rank_targets = {"D": 3, "C": 3, "B": 2, "A": 1, "S": 1}
    selected     = []

    for rank, count in rank_targets.items():
        pool = [t for t in MISSION_TEMPLATES if t["rank"] == rank]
        chosen = rng.sample(pool, min(count, len(pool)))

        for template in chosen:
            mission = _instantiate_mission(template, seed_date, rng)
            selected.append(mission)

    # Shuffle so rank order isn't always the same visual layout
    rng.shuffle(selected)
    return selected


def generate_priority_mission() -> dict:
    """Generate a single priority mission (server-wide, time-limited)."""
    template = random.choice(PRIORITY_MISSION_TEMPLATES)
    mission  = _instantiate_mission(template, datetime.utcnow().isoformat(), random)
    mission["is_priority"]  = True
    mission["expires_at"]   = (
        datetime.utcnow() + timedelta(hours=mission["time_hours"])
    ).isoformat()
    mission["issued_at"]    = datetime.utcnow().isoformat()
    return mission


def _instantiate_mission(template: dict, seed: str, rng) -> dict:
    """Fill in a mission template with concrete variable values."""
    mission = dict(template)
    var_choices = {}

    for var_name, options in template.get("vars", {}).items():
        if isinstance(options, list) and options:
            var_choices[var_name] = rng.choice(options)
        else:
            var_choices[var_name] = options

    mission["desc"]     = template["desc"].format(**var_choices)
    mission["name"]     = template["name"]
    mission["vars"]     = var_choices
    mission["mission_id"] = f"{template['id']}_{seed[:10]}"
    mission["progress"] = {}   # {player_id: contribution_amount}
    mission["completed"] = False
    mission["completed_at"] = None
    mission["completions"] = []  # List of player_ids who completed

    return mission


