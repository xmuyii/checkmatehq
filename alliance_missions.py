def get_or_generate_today_missions(alliance: dict) -> List[dict]:
    """
    Get today's mission pool for an alliance.
    Generates new ones if it's a new day.
    """
    today      = datetime.utcnow().strftime("%Y-%m-%d")
    pool       = alliance.get("mission_pool", {})

    if not isinstance(pool, dict):
        pool = {}

    if pool.get("date") == today and pool.get("missions"):
        return pool["missions"]

    # Generate fresh missions for today
    missions               = generate_daily_missions(today)
    alliance["mission_pool"] = {
        "date":         today,
        "missions":     missions,
        "selected_ids": [],   # Leader hasn't selected yet
    }
    return missions


def leader_select_missions(
    alliance: dict,
    leader_user: dict,
    mission_ids: List[str],
) -> Tuple[bool, str, dict]:
    """
    Alliance leader selects exactly 3 missions from the pool.
    Returns (success, message, updated_alliance)
    """
    role = leader_user.get("alliance_role", "MEMBER")
    if role != "LEADER":
        return False, "❌ Only the alliance leader can select missions.", alliance

    if len(mission_ids) != 3:
        return False, f"❌ Select exactly 3 missions. You selected {len(mission_ids)}.", alliance

    pool = alliance.get("mission_pool", {})
    if not pool.get("missions"):
        alliance = _init_pool(alliance)
        pool     = alliance["mission_pool"]

    available_ids = [m["mission_id"] for m in pool.get("missions", [])]

    for mid in mission_ids:
        if mid not in available_ids:
            return False, f"❌ Mission {mid} not in today's pool.", alliance

    pool["selected_ids"] = mission_ids
    alliance["mission_pool"] = pool

    selected_names = [
        m["name"] for m in pool["missions"]
        if m["mission_id"] in mission_ids
    ]
    return True, (
        f"✅ *3 missions assigned to your alliance:*\n"
        + "\n".join(f"  • {n}" for n in selected_names)
        + "\n\nMembers can now complete these to earn Alliance Points."
    ), alliance


def get_active_missions(alliance: dict) -> List[dict]:
    """Get the 3 missions currently active for members."""
    pool = alliance.get("mission_pool", {})
    if not isinstance(pool, dict):
        return []

    selected_ids = pool.get("selected_ids", [])
    all_missions = pool.get("missions", [])

    if not selected_ids:
        return []

    return [m for m in all_missions if m["mission_id"] in selected_ids]


def record_mission_progress(
    alliance: dict,
    player_id: str,
    objective_type: str,
    amount: int = 1,
    resource: str = None,
    sector_id: int = None,
) -> Tuple[dict, List[str]]:
    """
    Record player progress toward active missions.
    Called by other systems when relevant actions happen
    (resource collected, battle won, etc.)

    Returns (updated_alliance, list_of_completed_mission_names)
    """
    active       = get_active_missions(alliance)
    pool         = alliance.get("mission_pool", {})
    completed    = []

    for mission in pool.get("missions", []):
        if mission["mission_id"] not in pool.get("selected_ids", []):
            continue
        if mission.get("completed"):
            continue

        m_type     = mission.get("objective_type", "")
        m_resource = mission.get("objective_resource")

        # Check if this action matches the mission
        matches = False
        if m_type == objective_type:
            if m_resource and resource and m_resource != resource:
                matches = False
            else:
                matches = True

        if not matches:
            continue

        # Record progress
        if "progress" not in mission or not isinstance(mission.get("progress"), dict):
            mission["progress"] = {}

        mission["progress"][player_id] = mission["progress"].get(player_id, 0) + amount

        # Check completion
        target   = mission.get("vars", {}).get("amount", mission.get("vars", {}).get("minutes", 1))
        if isinstance(target, list):
            target = target[-1]  # Use the value that was chosen
        target   = mission["vars"].get("amount", target) if mission.get("vars") else target

        total_progress = sum(mission["progress"].values())

        if total_progress >= target and not mission.get("completed"):
            mission["completed"]    = True
            mission["completed_at"] = datetime.utcnow().isoformat()
            mission["completions"].append(player_id)
            completed.append(mission["name"])

            # Award AP to all contributors
            ap_reward = mission.get("ap_reward", 50)
            alliance  = _distribute_ap(alliance, mission["progress"], ap_reward)

    return alliance, completed


def _distribute_ap(alliance: dict, contributors: dict, total_ap: int) -> dict:
    """
    Distribute AP reward proportionally among contributors.
    Stored per-member for them to claim, or added to alliance pool.
    """
    if not contributors:
        return alliance

    # Equal split among all contributors
    share = max(1, total_ap // len(contributors))

    if "pending_ap_rewards" not in alliance:
        alliance["pending_ap_rewards"] = {}
    if not isinstance(alliance.get("pending_ap_rewards"), dict):
        alliance["pending_ap_rewards"] = {}

    for pid in contributors:
        alliance["pending_ap_rewards"][pid] = (
            alliance["pending_ap_rewards"].get(pid, 0) + share
        )

    return alliance


def claim_ap_rewards(alliance: dict, player_id: str, user: dict) -> Tuple[int, dict, dict]:
    """
    Player claims their pending AP rewards from completed missions.
    Returns (ap_claimed, updated_user, updated_alliance)
    """
    pending = alliance.get("pending_ap_rewards", {})
    if not isinstance(pending, dict):
        pending = {}

    amount = pending.pop(player_id, 0)
    if amount > 0:
        user["alliance_points"] = user.get("alliance_points", 0) + amount
        alliance["alliance_points"] = alliance.get("alliance_points", 0) + amount
        alliance["pending_ap_rewards"] = pending

    return amount, user, alliance


def accept_priority_mission(
    alliance: dict,
    leader_user: dict,
    priority_mission: dict,
) -> Tuple[bool, str, dict]:
    """Leader accepts a priority mission for the alliance."""
    role = leader_user.get("alliance_role", "MEMBER")
    if role != "LEADER":
        return False, "❌ Only the alliance leader can accept priority missions.", alliance

    if alliance.get("active_priority_mission"):
        existing = alliance["active_priority_mission"].get("name", "?")
        return False, f"❌ Already have an active priority mission: {existing}", alliance

    alliance["active_priority_mission"] = {
        **priority_mission,
        "accepted_at": datetime.utcnow().isoformat(),
        "progress":    {},
    }
    return True, (
        f"🚨 *Priority Mission Accepted!*\n"
        f"*{priority_mission['name']}*\n"
        f"{priority_mission['desc']}\n\n"
        f"Reward: {priority_mission['ap_reward']} AP + {priority_mission['gold_reward']} Gold"
        + (f" + {priority_mission.get('item_reward','').replace('_',' ').title()}" if priority_mission.get('item_reward') else "")
        + f"\n\nTime limit: {priority_mission['time_hours']}h"
    ), alliance


def _init_pool(alliance: dict) -> dict:
    """Initialise mission pool if missing."""
    today = datetime.utcnow().strftime("%Y-%m-%d")
    alliance["mission_pool"] = {
        "date":         today,
        "missions":     generate_daily_missions(today),
        "selected_ids": [],
    }
    return alliance


